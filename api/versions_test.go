// Package api_test checks the generated CRD across API versions.
package api_test

import (
	"os"
	"path/filepath"
	"testing"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"k8s.io/apimachinery/pkg/api/equality"
	"sigs.k8s.io/yaml"
)

// crdFile is generated by `make manifests`; `make test` runs that first.
var crdFile = filepath.Join("..", "config", "crd", "bases", "cardinality.telemetry-compass.com_cardinalitybudgets.yaml")

func loadCRD(t *testing.T) *apiextensionsv1.CustomResourceDefinition {
	t.Helper()
	data, err := os.ReadFile(crdFile)
	if err != nil {
		t.Fatalf("read %s: %v", crdFile, err)
	}
	crd := &apiextensionsv1.CustomResourceDefinition{}
	if err := yaml.UnmarshalStrict(data, crd); err != nil {
		t.Fatalf("parse %s: %v", crdFile, err)
	}
	return crd
}

func version(t *testing.T, crd *apiextensionsv1.CustomResourceDefinition, name string) apiextensionsv1.CustomResourceDefinitionVersion {
	t.Helper()
	for _, v := range crd.Spec.Versions {
		if v.Name == name {
			return v
		}
	}
	t.Fatalf("the CRD has no version %s", name)
	return apiextensionsv1.CustomResourceDefinitionVersion{}
}

// TestVersionsHaveTheSameSchema guards ADR 0017: without a conversion webhook the API server only rewrites
// apiVersion, so both versions must have exactly the same schema, subresources and printer columns. If this
// fails because a field changed, that change needs a new ADR and a conversion webhook first.
func TestVersionsHaveTheSameSchema(t *testing.T) {
	crd := loadCRD(t)
	alpha, beta := version(t, crd, "v1alpha1"), version(t, crd, "v1beta1")

	if !equality.Semantic.DeepEqual(alpha.Schema, beta.Schema) {
		t.Error("v1alpha1 and v1beta1 schemas differ; change both types files the same way (ADR 0017)")
	}
	if !equality.Semantic.DeepEqual(alpha.Subresources, beta.Subresources) {
		t.Error("v1alpha1 and v1beta1 subresources differ")
	}
	if !equality.Semantic.DeepEqual(alpha.AdditionalPrinterColumns, beta.AdditionalPrinterColumns) {
		t.Error("v1alpha1 and v1beta1 printer columns differ")
	}
	if !equality.Semantic.DeepEqual(alpha.SelectableFields, beta.SelectableFields) {
		t.Error("v1alpha1 and v1beta1 selectable fields differ")
	}
	if crd.Spec.Conversion != nil && crd.Spec.Conversion.Strategy != apiextensionsv1.NoneConverter {
		t.Errorf("conversion strategy is %s, want None", crd.Spec.Conversion.Strategy)
	}
}

// TestVersionRoles checks which version is stored and which is deprecated (ADR 0017).
func TestVersionRoles(t *testing.T) {
	crd := loadCRD(t)
	if len(crd.Spec.Versions) != 2 {
		t.Fatalf("the CRD has %d versions, want 2", len(crd.Spec.Versions))
	}
	alpha, beta := version(t, crd, "v1alpha1"), version(t, crd, "v1beta1")

	if !beta.Served || !beta.Storage || beta.Deprecated {
		t.Errorf("v1beta1: served=%t storage=%t deprecated=%t, want served, storage, not deprecated",
			beta.Served, beta.Storage, beta.Deprecated)
	}
	if !alpha.Served || alpha.Storage || !alpha.Deprecated || alpha.DeprecationWarning == nil {
		t.Errorf("v1alpha1: served=%t storage=%t deprecated=%t, want served, not storage, deprecated with a warning",
			alpha.Served, alpha.Storage, alpha.Deprecated)
	}
}
